-- DDL: Data Definition Language
-- CREATE(객체 생성), ALTER(구조 변경), DROP(객체 삭제). Oracle DDL은 암시적 COMMIT을 발생시키므로 일반 DML처럼 ROLLBACK할 수 없다.

-- 테이블 삭제: 자식 테이블부터 삭제합니다.
drop table order_item;
drop table orders;
drop table board;
drop table product;
drop table seller;
drop table member;

-- 테이블 생성: 참조되는 부모 테이블부터 생성합니다.

----------------------------------------------------------------
-- member 테이블 생성
create table member (
    member_id       varchar(15)     not null,
    member_name     varchar(20)     not null,    
    password        varchar(100)    not null,
    email           varchar(50),
    joined_at       date            default sysdate not null,
    constraint pk_member primary key (member_id),
    constraint uq_member_email unique (email)
);

----------------------------------------------------------------
-- seller 테이블 생성
create table seller (
    seller_id       int generated by default as identity not null,
    seller_name     varchar(200)    not null,   
    email           varchar2(254)   not null,
    phone           varchar2(15)    not null,
    registered_at   date            default sysdate not null,
    constraint pk_seller primary key (seller_id),
    constraint uq_seller_email unique (email)
);

----------------------------------------------------------------
-- product 테이블 생성
create table product (
    product_id      int generated by default as identity             not null,
    product_name    varchar(200)    not null,   
    price           int             not null,
    seller_id       int             not null,
    constraint pk_product primary key (product_id),
    constraint fk_product_seller foreign key (seller_id) references seller (seller_id)
);

----------------------------------------------------------------
-- board 테이블 생성
create table board (
    board_id    int generated by default as identity             not null,
    title       varchar(200)    not null,
    content     clob            not null,
    writer      varchar(15)     not null,
    writed_at        date            not null,
    product_id  int             not null,
    constraint pk_board primary key (board_id),
    constraint fk_board_member foreign key (writer) references member (member_id),
    constraint fk_board_product foreign key (product_id) references product (product_id)
);

----------------------------------------------------------------
-- orders 테이블 생성
create table orders (
    order_id        number(19,0)   generated by default as identity                      not null,
    member_id       varchar2(50 char)                   not null,
    ordered_at      timestamp default current_timestamp not null,
    constraint pk_orders primary key (order_id),
    constraint fk_orders_member foreign key (member_id) references member (member_id)
);

----------------------------------------------------------------
-- order_item 테이블 생성
create table order_item (
    order_id        int     not null,
    product_id      int     not null,
    quantity        int     not null,
    unit_price      int     not null,
    constraint pk_order_item primary key (order_id, product_id),
    constraint fk_orders_item_orders foreign key (order_id) references orders (order_id),
    constraint fk_orders_item_product foreign key (product_id) references product (product_id) 
);
